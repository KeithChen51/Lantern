// Usage: node sync-masks.mjs <design-consultant directory> [--check]
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const [catalog, option] = process.argv.slice(2);
if (!catalog || (option && option !== "--check")) throw new Error("Expected a catalog directory and optionally --check");

const partNames = [
  ...["orbit-back", "wordmark", "focus", "orbit-front"].map(part => `space-mark-parametric-${part}`),
  ...["standard", "compact"].flatMap(size => ["powered-by", "ai", "native"].map(part => `formal-${size}-${part}`)),
];
const declarations = await Promise.all(partNames.map(async name => {
  const svg = await readFile(join(catalog, "templates", "brand-attribution", `${name}-mask.svg`));
  return `  --${name}: url("data:image/svg+xml;base64,${svg.toString("base64")}");`;
}));
const css = `/* Generated by sync-masks.mjs from the approved SVG masks. */\n.space-signature {\n${declarations.join("\n")}\n}\n`;
const destination = new URL("./masks.css", import.meta.url);
if (option === "--check") {
  if ((await readFile(destination, "utf8")).replaceAll("\r\n", "\n") !== css) throw new Error("Signature masks differ from the catalog");
} else {
  await writeFile(destination, css);
}
